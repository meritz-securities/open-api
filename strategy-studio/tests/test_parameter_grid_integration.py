"""Independent grid integration oracles: hand arithmetic, real Runtime and MCP.

No expected value is generated by the optimizer or accounting implementation.
All inputs are three generated OHLC observations, never customer market data.
"""
import asyncio
import copy
import json
import os
import subprocess
import sys

import pytest
from fastmcp import Client, FastMCP

from runtime.mcp import register_platform
from runtime.service import StrategyRuntime


def isolated_process_env():
    environment = {key: value for key, value in os.environ.items()
                   if not key.startswith(('MERITZ_', 'OPENAI_', 'ANTHROPIC_'))}
    environment.update(MERITZ_NO_ENV_FILE='1', MERITZ_READ_ONLY='1')
    return environment


def seed(root, prices=(100, 110, 120)):
    service = StrategyRuntime(root)
    definition = {
        'schemaVersion': 1, 'kind': 'dsl', 'name': 'Three-bar independent oracle',
        'entry': {'op': 'gt', 'left': {'type': 'field', 'field': 'close'},
                  'right': {'type': 'constant', 'value': 0}},
        'exit': {'op': 'lt', 'left': {'type': 'field', 'field': 'close'},
                 'right': {'type': 'constant', 'value': 0}},
        'quantity': 1, 'allowPyramiding': False,
    }
    revision = service.save_strategy(definition)
    data = service.import_data([
        {'date': f'2025-01-0{index + 1}', 'open': price, 'high': price,
         'low': price, 'close': price}
        for index, price in enumerate(prices)
    ], {'kind': 'imported', 'label': 'GENERATED grid arithmetic oracle'})
    baseline = service.run(revision['id'], data['id'], {
        'initialCash': 1000, 'feeBps': 0, 'taxBps': 0, 'slippageBps': 0,
    })
    return service, baseline


def assert_buy_and_hold(run, quantity, last_close):
    # Day-one close triggers a fill at day-two OPEN=110. No pyramiding:
    # cash=1000-110*q; end equity=cash+last_close*q; no realized P/L.
    report = run['report']
    assert report['metrics']['finalEquity'] == 1000 + quantity * (last_close - 110)
    assert report['metrics']['totalReturnPct'] == pytest.approx(quantity * (last_close - 110) / 10)
    assert report['finalPortfolio'] == pytest.approx({
        'cash': 1000 - 110 * quantity, 'shares': quantity,
        'equity': 1000 + quantity * (last_close - 110), 'averageCost': 110,
        'realizedPnl': 0, 'unrealizedPnl': quantity * (last_close - 110),
        'lastClose': last_close,
    })
    assert len(report['trades']) == 1
    fill = report['trades'][0]
    assert (fill['signalDate'], fill['date'], fill['side']) == ('2025-01-01', '2025-01-02', 'BUY')
    assert (fill['price'], fill['quantity'], fill['cashAfter']) == (110, quantity, 1000 - 110 * quantity)
    assert fill['fee'] == fill['tax'] == 0


def test_grid_real_engine_oracle_baseline_preservation_reopen_and_cli(tmp_path):
    service, baseline = seed(tmp_path)
    original_revision = copy.deepcopy(service.get_strategy(baseline['revisionId']))
    original_data = copy.deepcopy(service.store.get('dataset', baseline['datasetId']))
    assert_buy_and_hold(baseline, 1, 120)
    record = service.dispatch('validate_robustness', {
        'runId': baseline['id'], 'method': 'parameter_grid',
        'options': {'axes': [{'path': 'quantity', 'values': [2, 3]}], 'maxEvaluations': 2},
    })
    result = record['result']
    assert result['status'] == 'completed'
    assert result['candidateCount'] == 2
    assert result['bestCandidateIndex'] == 2
    assert result['baselineComparable'] is True
    assert result['bestCandidateImproved'] is True
    assert result['baselineReturnPct'] == pytest.approx(1)
    assert result['holdoutContaminated'] is True
    assert [item['parameterValues'] for item in result['results']] == [{'quantity': 2}, {'quantity': 3}]
    for index, item in enumerate(result['results'], 2):
        assert item['status'] == 'succeeded'
        child = service.get_run(item['result']['runId'])
        assert_buy_and_hold(child, index, 120)
        assert child['datasetId'] == baseline['datasetId']
        assert child['settings'] == baseline['settings']
        assert child['manifest']['dataHash'] == baseline['manifest']['dataHash']
        assert child['parentRunId'] == baseline['id']
        assert child['validationJobId'] == record['jobId']
    reopened = StrategyRuntime(tmp_path)
    assert reopened.get_validation(record['id']) == record
    assert reopened.get_run(baseline['id']) == baseline
    assert reopened.get_strategy(baseline['revisionId']) == original_revision
    assert reopened.store.get('dataset', baseline['datasetId']) == original_data
    # CLI reuses exactly the same persisted data and parameter-grid implementation.
    process = subprocess.run([
        sys.executable, '-m', 'runtime.cli', 'validate_robustness', '--root', str(tmp_path),
        '--arguments', json.dumps({'runId': baseline['id'], 'method': 'parameter_grid',
                                  'options': {'axes': [{'path': 'quantity', 'values': [2, 3]}]}}),
    ], env=isolated_process_env(), capture_output=True, text=True, timeout=30)
    assert process.returncode == 0, process.stderr
    replay = json.loads(process.stdout)['result']['result']
    assert [row['result']['metrics']['finalEquity'] for row in replay['results']] == [1020, 1030]


def test_mcp_advertises_grid_and_keeps_zero_return_candidates_in_axis_order(tmp_path):
    service, baseline = seed(tmp_path)
    async def check():
        server = FastMCP('independent-grid-integration')
        register_platform(server, None, None, service)
        async with Client(server) as client:
            tool = next(tool for tool in await client.list_tools() if tool.name == 'meritz_strategy_robustness')
            assert 'parameter_grid' in tool.inputSchema['properties']['method']['enum']
            record = (await client.call_tool('meritz_strategy_robustness', {
                'runId': baseline['id'], 'method': 'parameter_grid', 'options': {'axes': [
                    {'path': 'quantity', 'values': [2, 3]},
                    {'path': 'entry.right.value', 'values': [0, 115]},
                ]},
            })).data
            restored = (await client.call_tool('meritz_strategy_validation_result', {'validationId': record['id']})).data
            assert restored == record
            progress = (await client.call_tool('meritz_strategy_validation_job', {'jobId': record['jobId']})).data
            assert progress['status'] == 'succeeded'
            assert [item['result']['runId'] for item in progress['candidateResults']] == [item['result']['runId'] for item in record['result']['results']]
            return record
    record = asyncio.run(check())
    result = record['result']
    assert [row['parameterValues'] for row in result['results']] == [
        {'quantity': 2, 'entry.right.value': 0}, {'quantity': 2, 'entry.right.value': 115},
        {'quantity': 3, 'entry.right.value': 0}, {'quantity': 3, 'entry.right.value': 115},
    ]
    # Threshold115 first becomes true at the LAST close120, so no later bar can fill.
    assert [row['result']['metrics']['finalEquity'] for row in result['results']] == [1020, 1000, 1030, 1000]
    assert result['bestCandidateIndex'] == 3
    assert [row['result']['metrics']['tradeCount'] for row in result['results']] == [1, 0, 1, 0]
    assert service.get_run(baseline['id']) == baseline


def test_all_candidates_worse_than_original_are_retained(tmp_path):
    service, baseline = seed(tmp_path, prices=(100, 110, 90))
    assert_buy_and_hold(baseline, 1, 90)
    record = service.validate_robustness(baseline['id'], 'parameter_grid', {
        'axes': [{'path': 'quantity', 'values': [3, 2]}],
    })
    result = record['result']
    assert result['status'] == 'completed'
    assert result['baselineReturnPct'] == pytest.approx(-2)
    assert [row['result']['metrics']['totalReturnPct'] for row in result['results']] == pytest.approx([-6, -4])
    assert result['bestCandidateIndex'] == 2
    assert result['baselineComparable'] is True
    assert result['bestCandidateImproved'] is False
    for item, quantity in zip(result['results'], [3, 2]):
        child = service.get_run(item['result']['runId'])
        assert_buy_and_hold(child, quantity, 90)
        assert child['report']['metrics']['finalEquity'] < baseline['report']['metrics']['finalEquity']
    assert StrategyRuntime(tmp_path).get_validation(record['id']) == record


def test_process_exit_after_saved_fill_recovers_progress_beyond_recent_summary(tmp_path):
    service, baseline = seed(tmp_path)
    # Terminate AFTER the real child is committed but BEFORE the parent callback
    # can append its ID or update an in-memory progress list. This is an actual
    # process exit, not a synthesized terminal job fixture.
    script = '''
import os, sys
from runtime.service import StrategyRuntime
runtime = StrategyRuntime(sys.argv[1])
original = runtime._run_locked
def stop_after_persisted_child(*args, **kwargs):
    original(*args, **kwargs)
    os._exit(73)
runtime._run_locked = stop_after_persisted_child
runtime.validate_robustness(sys.argv[2], 'parameter_grid',
    {'axes': [{'path': 'quantity', 'values': [2, 3]}]})
'''
    process = subprocess.run([sys.executable, '-c', script, str(tmp_path), baseline['id']],
                             env=isolated_process_env(),
                             capture_output=True, text=True, timeout=30)
    assert process.returncode == 73, process.stderr
    reopened = StrategyRuntime(tmp_path)
    job = reopened.list_runs()['validationJobs'][0]
    assert job['status'] == 'interrupted'
    # Populate more than the default recent listing limit. Recovery must query
    # the exact job relationship rather than searching only the last 100 runs.
    for index in range(110):
        reopened.store.put('run', f'unrelated-later-{index:03}', {
            'id': f'unrelated-later-{index:03}', 'status': 'failed',
            'validationJobId': 'another-job', 'error': 'test-only unrelated history',
            'createdAt': '2099-01-01T00:00:00Z',
        })
    recovered = reopened.dispatch('get_validation_job', {'jobId': job['id']})
    assert recovered['status'] == 'interrupted'
    assert recovered['candidateCount'] == 2
    assert [row['status'] for row in recovered['candidateResults']] == ['succeeded', 'not_run']
    completed = recovered['candidateResults'][0]
    assert completed['parameterValues'] == {'quantity': 2}
    assert completed['result']['metrics']['finalEquity'] == 1020
    assert recovered['childRunIds'] == [completed['runId']]
    assert_buy_and_hold(reopened.get_run(completed['runId']), 2, 120)
    assert reopened.get_run(baseline['id']) == baseline
    assert reopened.get_validation_job(job['id']) == recovered
    assert reopened.store.list('validation') == []


def test_progress_refuses_child_whose_strategy_hash_does_not_match_plan(tmp_path, monkeypatch):
    service, baseline = seed(tmp_path)
    record = service.validate_robustness(baseline['id'], 'parameter_grid', {
        'axes': [{'path': 'quantity', 'values': [2, 3]}],
    })
    original_get = service.store.get
    def changed_plan(kind, ident):
        value = original_get(kind, ident)
        if kind == 'validation-job' and ident == record['jobId']:
            value = copy.deepcopy(value)
            value['candidatePlan'][0]['strategyHash'] = '0' * 64
        return value
    monkeypatch.setattr(service.store, 'get', changed_plan)
    with pytest.raises(ValueError, match='match.*plan'):
        service.get_validation_job(record['jobId'])
